b = "hello world"
print(b[2:5]) #returns the characters from position 2 to 5 (not included)

#slice from the start
b = "hello world"
print(b[:5]) #returns the characters from the start to position 5 (not included)

#slice to the end
b = "hello world"
print(b[2:]) #returns the characters from position 2 to the end

#negative indexing
b = "hello world"
print(b[-5:-2]) #returns the characters from position 5 (from the end) to position 2 (from the end, not included)

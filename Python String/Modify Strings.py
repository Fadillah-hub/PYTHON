a = "hello, world"
print(a.upper()) #returns the string in upper case

#lower case
a = "HELLO, WORLD"
print(a.lower()) #returns the string in lower case

#remove whitespace
a = " hello, world "
print(a.strip()) #returns the string without whitespace at the beginning or end

#replace string
a = "hello, world"
print(a.replace("h", "j")) #returns a string where "h" is replaced with "j"

#split string
a = "hello, world"
print(a.split(",")) #returns a list where the string is split at the comm